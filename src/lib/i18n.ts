export function occasionText(id: OccasionId, lang: Lang) {
  if (lang === "pt") return PT_OCCASIONS[id];
  const o = OCCASIONS.find((x) => x.id === id)!;
  return { label: o.label, titleHint: o.titleHint, lines: o.lines };
}
export function revealText(id: RevealId, lang: Lang) {
  return lang === "pt" ? PT_REVEALS[id] : REVEALS.find((r) => r.id === id)!;
}
export function colorLabel(id: ColorId, lang: Lang) {
  return lang === "pt" ? PT_COLORS[id] : COLORS.find((c) => c.id === id)!.label;
}
export function themeLabel(id: ThemeId, lang: Lang) {
  return lang === "pt" ? PT_THEMES[id] : THEMES.find((t) => t.id === id)!.label;
}
